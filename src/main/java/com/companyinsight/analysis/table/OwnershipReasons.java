package com.companyinsight.analysis.table;

import java.util.Optional;
import java.util.Set;

/**
 * 지분 보고의 변동 사유(보고사유, 변경원인)에 적히는 낱말을 매수, 매도, 매매가 아닌 변동으로 나눈다.
 * 낱말은 서식이 정해 둔 글자이고 끝에 늘었는지(+) 줄었는지(-)가 붙는다 (예: "장내매수(+)").
 *
 * <p>매수·매도로 보는 것은 보고자가 값을 치르고 시장이나 상대방에게서 사고판 것뿐이다(장내, 장외, 시간외, 신고대량매매, 공개매수).
 * 회사가 준 주식(상여금, 주식매수선택권), 새로 생긴 주식(유상·무상 신주, 전환), 주고받은 주식(증여, 상속, 대여),
 * 보고 대상이 되거나 빠진 것(신규 선임, 퇴임, 신규 보고)은 매매가 아니다.
 *
 * <p>여기에 없는 낱말은 어느 쪽인지 추측하지 않는다.
 */
final class OwnershipReasons {

	/** 변동 사유의 갈래. */
	enum Kind {

		/** 사들였다 */
		BUY,

		/** 팔았다 */
		SELL,

		/** 매매가 아닌 변동 */
		NOT_TRADE
	}

	private static final Set<String> BUY = Set.of("장내매수(+)", "장외매수(+)", "시간외매매(+)", "신고대량매매(+)", "공개매수(+)");

	private static final Set<String> SELL = Set.of("장내매도(-)", "장외매도(-)", "시간외매매(-)", "신고대량매매(-)", "공개매수청약(-)");

	private static final Set<String> NOT_TRADE = Set.of(
		// 보고 대상이 되거나 빠짐
		"신규보고(+)", "신규선임(+)", "신규선임(유상취득)(+)", "신규선임(무상취득)(+)", "신규주요주주(+)", "신규상장(+)",
		"신규상장(유상취득)(+)", "신규상장(무상취득)(+)", "신규등록(+)", "임원퇴임(-)", "특별관계해소(-)",
		// 회사가 준 주식
		"자사주상여금(+)", "주식매수선택권(+)", "주식매수선택권부여(+)", "주식매수선택권부여취소(-)", "주식매수선택권행사(+)",
		"주식매수선택권행사(-)",
		// 새로 생기거나 바뀐 주식
		"유상신주취득(+)", "무상신주취득(+)", "제3자배정유상증자(+)", "출자전환", "주식배당(+)", "합병(+)", "합병(-)", "주식병합",
		"주식분할", "자본감소", "주식소각", "전환등(-)", "전환사채의권리행사(+)", "신주인수권사채의권리행사(+)", "교환사채의권리행사(+)",
		"교환(-)", "전환권등소멸(-)", "CB인수(+)", "BW인수(+)", "행사가액조정", "주식매수청구권행사(+)", "주식매수청구권행사(-)",
		// 주고받은 주식
		"증여(-)", "수증(+)", "수증취소(-)", "상속(+)", "피상속(-)", "대여(-)", "차입(+)", "담보주식처분권보유",
		// 서식이 "기타"로 묶은 것
		"기타(+)", "기타(-)");

	private OwnershipReasons() {
	}

	/**
	 * 변동 사유 칸의 낱말이 어느 갈래인지.
	 *
	 * @return 정해 둔 낱말이 아니면 비어 있음
	 */
	static Optional<Kind> kindOf(String cell) {
		String word = Cells.compact(cell);
		if (BUY.contains(word)) {
			return Optional.of(Kind.BUY);
		}
		if (SELL.contains(word)) {
			return Optional.of(Kind.SELL);
		}
		return NOT_TRADE.contains(word) ? Optional.of(Kind.NOT_TRADE) : Optional.empty();
	}
}
